/**
 * Markdown snapshot of a computed chart, designed to paste into an AI
 * conversation (user test part 2: "take this snapshot of your chart …
 * a personality profile using IFS — like we did before with Claude").
 * Raw factors only, no interpretations: the receiving model should
 * work from the astrology, not from our prose.
 */
export function chartSnapshot(chart: Chart, meta: ChartMeta): string {
  // drop the U+FE0E text-presentation selector that fmtDegInSign embeds
  const strip = (s: string) => s.replace(/︎/g, '').trim();
  const lines: string[] = [];
  lines.push(`# Natal chart — ${meta.name || 'unnamed'}`);
  lines.push(`Born ${meta.date} ${meta.time} (UTC${meta.offsetMinutes >= 0 ? '+' : ''}${Math.floor(meta.offsetMinutes / 60)}:${String(Math.abs(meta.offsetMinutes % 60)).padStart(2, '0')}) · ${meta.place.name}, ${meta.place.country} · Placidus houses, tropical zodiac.`);
  if (meta.accuracy !== 'exact') {
    lines.push(`Birth-time accuracy: ${meta.accuracy} — treat houses/angles accordingly.`);
  }
  lines.push('', '## Angles');
  lines.push(`- Ascendant: ${strip(fmtDegInSign(chart.houses.asc))}`);
  lines.push(`- Midheaven: ${strip(fmtDegInSign(chart.houses.mc))}`);
  lines.push('', '## Positions');
  for (const p of chart.positions) {
    lines.push(`- ${BODY_NAME[p.body]}: ${strip(fmtDegInSign(p.lon))}, house ${p.house}${p.speed < 0 ? ', retrograde' : ''}`);
  }
  lines.push('', '## Aspects (strongest first, with orb)');
  for (const a of chart.aspects) {
    lines.push(`- ${BODY_NAME[a.a]} ${a.def.name} ${BODY_NAME[a.b]} (orb ${strip(fmtOrb(a.orb))}, ${a.applying ? 'applying' : 'separating'})`);
  }
  const sun = chart.positions.find(p => p.body === 'sun');
  const moon = chart.positions.find(p => p.body === 'moon');
  if (sun && moon) {
    const ph = lunationPhase(sun.lon, moon.lon);
    lines.push('', `Lunation phase at birth: ${ph.name}, `
      + `${ph.waxing ? 'waxing' : 'waning'} (Sun–Moon ${Math.round(ph.angle)}°).`);
  }
  const tensions = tensionReport(chart);
  if (tensions.length) {
    lines.push('', '## Strongest internal contradictions (computed)');
    for (const t of tensions) {
      lines.push(`- ${BODY_NAME[t.a.a]} ${t.a.def.name} ${BODY_NAME[t.a.b]} vs ${BODY_NAME[t.b.a]} ${t.b.def.name} ${BODY_NAME[t.b.b]} — opposed pulls on "${t.theme}"`);
    }
  }
  const emphases = signEmphasis(chart);
  if (emphases) lines.push('', emphases);
  lines.push('', '---',
    'Snapshot generated by Astrodynamics (positions computed offline against JPL/Swiss-validated ephemerides). Interpretations deliberately omitted — please interpret from the raw factors above.');
  return lines.join('\n');
}

/**
 * Synastry snapshot for AI conversations (user request 2026-07-05:
 * "copy for synastry not just natal"): both charts compactly, then the
 * relationship structures. Raw factors only.
 */
export function synastrySnapshot(
  a: Chart, aMeta: ChartMeta,
  b: Chart, bLabel: string,
  cross: CrossAspect[],
  overlaysBinA: Overlay[],
  midsAonB: MidpointContact[],
  midsBonA: MidpointContact[],
): string {
  const strip = (s: string) => s.replace(/︎/g, '').trim();
  const lines: string[] = [];
  const aName = aMeta.name || 'Person A';
  lines.push(`# Synastry — ${aName} × ${bLabel}`);
  lines.push('', `## ${aName} (positions, house)`);
  for (const p of a.positions) {
    lines.push(`- ${BODY_NAME[p.body]}: ${strip(fmtDegInSign(p.lon))}, H${p.house}${p.speed < 0 ? ' ℞' : ''}`);
  }
  lines.push(`- ASC ${strip(fmtDegInSign(a.houses.asc))} · MC ${strip(fmtDegInSign(a.houses.mc))}`);
  lines.push('', `## ${bLabel} (positions, house)`);
  for (const p of b.positions) {
    lines.push(`- ${BODY_NAME[p.body]}: ${strip(fmtDegInSign(p.lon))}, H${p.house}${p.speed < 0 ? ' ℞' : ''}`);
  }
  lines.push(`- ASC ${strip(fmtDegInSign(b.houses.asc))} · MC ${strip(fmtDegInSign(b.houses.mc))}`);
  lines.push('', '## Inter-aspects (strongest first; synastry orbs)');
  for (const x of cross) {
    lines.push(`- ${aName}'s ${BODY_NAME[x.a]} ${x.def.name} ${bLabel}'s ${BODY_NAME[x.b]} (orb ${strip(fmtOrb(x.orb))})`);
  }
  const ovl = overlaysBinA.filter(o =>
    ['sun', 'moon', 'venus', 'mars', 'saturn', 'jupiter', 'juno'].includes(o.body));
  if (ovl.length) {
    lines.push('', `## House overlays — ${bLabel}'s bodies in ${aName}'s houses`);
    for (const o of ovl) lines.push(`- ${BODY_NAME[o.body]} → house ${o.house}`);
  }
  const midLine = (m: MidpointContact, who: string, whose: string) =>
    `- ${who}'s ${BODY_NAME[m.body]} on ${whose}'s ${BODY_NAME[m.pair[0]]}/${BODY_NAME[m.pair[1]]} midpoint (90° dial, orb ${strip(fmtOrb(m.orb))})`;
  if (midsAonB.length || midsBonA.length) {
    lines.push('', '## Midpoint contacts (Ebertin)');
    for (const m of midsAonB) lines.push(midLine(m, bLabel, aName));
    for (const m of midsBonA) lines.push(midLine(m, aName, bLabel));
  }
  lines.push('', '---',
    'Snapshot generated by Astrodynamics. Interpretations deliberately omitted — please interpret from the raw factors above (e.g. an IFS-informed couple profile: map each chart\'s part-structures, then read inter-aspects as parts-to-parts contacts, reciprocal healing contracts, and friction loops).');
  return lines.join('\n');
}

/**
 * Transit snapshot for AI conversations. 'you' target: natal + the
 * transiting sky + transits to the natal. 'couple' target (astro-ghw)
 * additionally carries the partner's natal, the synastry contacts between the
 * two charts, the transits to the partner, the transits that touch a point in
 * a synastry contact, and the Sun/Moon midpoint hits. No composite: transits
 * to the composite are the Composite tab's.
 */
export function transitSnapshot(opts: {
  natal: Chart; meta: ChartMeta; sky: Chart; when: string;
  toNatal: CrossAspect[];
  couple?: {
    partner: Chart; partnerName: string;
    /** Synastry contacts, strongest first (a: the native's body, b: the partner's). */
    synastry: CrossAspect[];
    toPartner: CrossAspect[];
    activated: ActivatedContact[];
    midpointHits: { whose: 'A' | 'B'; body: BodyKey; orb: number }[];
  } | null;
}): string {
  const strip = (s: string) => s.replace(/︎/g, '').trim();
  const L: string[] = [];
  const name = opts.meta.name || 'unnamed';
  const natalPos = (c: Chart) => c.positions.map(p =>
    `- ${BODY_NAME[p.body]}: ${strip(fmtDegInSign(p.lon))}, H${p.house}${p.speed < 0 ? ' ℞' : ''}`);
  const skyPos = (c: Chart) => c.positions.map(p =>
    `- ${BODY_NAME[p.body]}: ${strip(fmtDegInSign(p.lon))}${p.speed < 0 ? ' ℞' : ''}`);
  const angles = (c: Chart) => `- ASC ${strip(fmtDegInSign(c.houses.asc))} · MC ${strip(fmtDegInSign(c.houses.mc))}`;
  const xLine = (x: CrossAspect, target: string) =>
    `- transiting ${BODY_NAME[x.a]} ${x.def.name} ${target} ${BODY_NAME[x.b]} (orb ${strip(fmtOrb(x.orb))}, ${x.applying ? 'applying' : 'separating'})`;

  L.push(`# Transits — ${name}`);
  L.push(`Sky of ${opts.when}, computed for ${opts.meta.place.name}, ${opts.meta.place.country}. Tropical zodiac.`);
  L.push('', `## ${name} natal positions`, ...natalPos(opts.natal), angles(opts.natal));
  L.push('', `## Transiting sky (${opts.when})`, ...skyPos(opts.sky));
  L.push('', `## Transits to ${name}'s natal (strongest first)`);
  for (const x of opts.toNatal) L.push(xLine(x, 'natal'));

  if (opts.couple) {
    const { partner, partnerName, synastry, toPartner, activated, midpointHits } = opts.couple;
    const contact = (c: CrossAspect) =>
      `${name}'s ${BODY_NAME[c.a]} ${c.def.name} ${partnerName}'s ${BODY_NAME[c.b]} (orb ${strip(fmtOrb(c.orb))})`;
    L.push('', `## ${partnerName} natal positions`, ...natalPos(partner), angles(partner));
    L.push('', '## Synastry contacts (background: the standing contacts between the two charts, strongest first)');
    for (const c of synastry) L.push(`- ${contact(c)}`);
    L.push('', `## Transits to ${partnerName}'s natal (strongest first)`);
    for (const x of toPartner) L.push(xLine(x, `${partnerName}'s`));
    L.push('', '## Transits touching a synastry contact');
    if (!activated.length) L.push('- none within orb');
    for (const a of activated) {
      const owner = a.whose === 'A' ? name : partnerName;
      L.push(`- transiting ${BODY_NAME[a.transit.a]} ${a.transit.def.name} ${owner}'s ${BODY_NAME[a.transit.b]} (orb ${strip(fmtOrb(a.transit.orb))}, ${a.transit.applying ? 'applying' : 'separating'}), part of ${a.contacts.map(contact).join('; and of ')}`);
    }
    if (midpointHits.length) {
      L.push('', "## Transits to either person's Sun/Moon midpoint (90° dial)");
      for (const h of midpointHits) L.push(`- transiting ${BODY_NAME[h.body]} on ${h.whose === 'A' ? name : partnerName}'s Sun/Moon midpoint (orb ${strip(fmtOrb(h.orb))})`);
    }
  }
  L.push('', '---',
    'Snapshot generated by Astrodynamics. Interpretations deliberately omitted — please interpret from the raw factors above.');
  return L.join('\n');
}

/**
 * Composite snapshot for AI conversations: the midpoint chart of the
 * relationship, plus both people's natal positions for grounding.
 */
export function compositeSnapshot(
  composite: Chart, aName: string, a: Chart, b: Chart, bName: string,
  /** The Composite tab's "Transits on" option (astro-ghw): the sky of a date on the composite. */
  transits?: { when: string; place: string; toComposite: CrossAspect[] } | null,
): string {
  const strip = (s: string) => s.replace(/︎/g, '').trim();
  const L: string[] = [];
  const natalPos = (c: Chart) => c.positions.map(p =>
    `- ${BODY_NAME[p.body]}: ${strip(fmtDegInSign(p.lon))}, H${p.house}${p.speed < 0 ? ' ℞' : ''}`);
  L.push(`# Composite (midpoint) chart — ${aName} × ${bName}`);
  L.push('The chart of the relationship itself (midpoint method) — a constructed chart, not a real sky; houses and angles are weaker evidence than planets and aspects.');
  L.push('', '## Composite positions');
  for (const p of composite.positions) {
    L.push(`- ${BODY_NAME[p.body]}: ${strip(fmtDegInSign(p.lon))}, H${p.house}`);
  }
  L.push(`- ASC ${strip(fmtDegInSign(composite.houses.asc))} · MC ${strip(fmtDegInSign(composite.houses.mc))}`);
  L.push('', '## Composite aspects (strongest first)');
  for (const x of composite.aspects) {
    L.push(`- ${BODY_NAME[x.a]} ${x.def.name} ${BODY_NAME[x.b]} (orb ${strip(fmtOrb(x.orb))})`);
  }
  L.push('', `## ${aName} natal (positions)`, ...natalPos(a));
  L.push('', `## ${bName} natal (positions)`, ...natalPos(b));
  if (transits) {
    L.push('', `## Transits to the composite (sky of ${transits.when}, computed for ${transits.place}; strongest first)`);
    if (!transits.toComposite.length) L.push('- none within orb');
    for (const x of transits.toComposite) {
      L.push(`- transiting ${BODY_NAME[x.a]} ${x.def.name} composite ${BODY_NAME[x.b]} (orb ${strip(fmtOrb(x.orb))}, ${x.applying ? 'applying' : 'separating'})`);
    }
  }
  L.push('', '---',
    'Snapshot generated by Astrodynamics. Interpretations deliberately omitted — please interpret from the raw factors above (composite read as the relationship as a unit, not either person).');
  return L.join('\n');
}

/** One visible planet in the orrery, pre-formatted by the view. */
export interface OrreryPlanetSnap {
  name: string;
  /** Geocentric longitude, formatted (e.g. "12°34′ ♏ Scorpio"). */
  lon: string;
  /** Apparent motion, degrees per day (negative = retrograde). */
  speed: number;
  status: 'direct' | 'retrograde' | 'stationary';
  /** Elongation from the Sun in degrees; positive = east (evening sky). */
  elong: number;
  /** The current or next retrograde spell, if one is in range. */
  next?: {
    inRetro: boolean;
    srDate: string; srLon: string;
    sdDate: string; sdLon: string;
    arc: number; days: number;
  };
}

/** The Moon and the eclipses round the date shown, pre-formatted by the view. */
export interface OrreryMoonSnap {
  lon: string; lat: number; speed: number; distKm: number;
  phase: string; lit: number; elong: number; waxing: boolean; age: number;
  /** The Sun's distance from the nearer lunar node, degrees. */
  sunNode: number;
  quarters: { name: string; date: string }[];
  /** Where the local eclipse facts are for. */
  place: string;
  lunar: { date: string; kind: string; start: string; end: string; totality?: string; moonAlt: number; now: boolean };
  localSolar: { date: string; kind: string; covered: number; sunAlt: number; start: string; end: string; now: boolean };
  globalSolar: {
    date: string; kind: string; greatest?: string;
    /** Where the shadow's axis meets the Earth (total and annular eclipses). */
    centralLine: { time: string; at: string }[];
  };
}

/**
 * Snapshot of the orrery (Retrograde tab / standalone page) for AI
 * conversations: the date shown, each visible planet's apparent position and
 * motion, its retrograde spell, and the recent event log. Astronomical facts
 * only; no personal data.
 */
export function orrerySnapshot(o: {
  date: string;
  model: 'ephemeris' | 'circular';
  view: 'earth' | 'sun';
  /** The Sun's geocentric longitude, formatted. */
  sun: string;
  planets: OrreryPlanetSnap[];
  moon?: OrreryMoonSnap;
  events: { date: string; text: string }[];
}): string {
  const strip = (s: string) => s.replace(/︎/g, '').trim();
  const L: string[] = [];
  L.push(`# Orrery — the sky on ${o.date}`);
  L.push('Planets as seen from Earth against the zodiac (geocentric, tropical longitudes). '
    + (o.model === 'ephemeris'
      ? 'Orbit model: true orbits, from the same ephemeris as the charts.'
      : 'Orbit model: idealised circular orbits (station dates can be off by a few days).')
    + ` Display: ${o.view === 'earth' ? 'Earth' : 'Sun'} at the centre.`);
  L.push('', `The Sun: ${strip(o.sun)}.`);
  L.push('', '## Planets shown');
  if (!o.planets.length) L.push('- (none selected)');
  for (const p of o.planets) {
    const side = p.elong >= 0 ? 'east of the Sun (evening sky)' : 'west of the Sun (morning sky)';
    L.push(`- ${p.name}: ${strip(p.lon)} · ${p.status}, ${p.speed >= 0 ? '+' : '−'}${Math.abs(p.speed).toFixed(3)}°/day · ${Math.abs(p.elong).toFixed(1)}° ${side}`);
    if (p.next) {
      const n = p.next;
      L.push(`  - ${n.inRetro ? 'Turned retrograde' : 'Next turns retrograde'} ${n.srDate} at ${strip(n.srLon)}; `
        + `turns direct ${n.sdDate} at ${strip(n.sdLon)}; retrograde arc ${n.arc.toFixed(1)}° over ${n.days.toFixed(1)} days.`);
    }
  }
  if (o.moon) {
    const m = o.moon;
    L.push('', '## The Moon (from the ephemeris, whichever orbit model is shown)',
      `- ${m.phase}, ${Math.round(m.lit * 100)}% lit; ${m.elong.toFixed(1)}° from the Sun (${m.waxing ? 'waxing' : 'waning'}), day ${m.age.toFixed(1)} of the synodic month`,
      `- ${strip(m.lon)}, ${Math.abs(m.lat).toFixed(2)}° ${m.lat >= 0 ? 'north' : 'south'} of the ecliptic, moving ${m.speed.toFixed(2)}°/day`,
      `- Distance ${Math.round(m.distKm).toLocaleString('en-GB')} km (centre to centre)`,
      `- The Sun is ${m.sunNode.toFixed(1)}° from the nearer lunar node${m.sunNode < 18 ? ' (eclipse season: New and Full Moons now can eclipse)' : ''}`,
      `- Next: ${m.quarters.map(q => `${q.name} ${q.date}`).join('; ')}`);
    const now = (b: boolean) => (b ? ' **Under way at the date shown.**' : '');
    const lu = m.lunar, ls = m.localSolar, g = m.globalSolar;
    L.push('', `## Eclipses (in progress at the date shown, or next; computed with astronomy-engine)`,
      `- Lunar: ${lu.kind}, peak ${lu.date}; penumbral contacts ${lu.start}–${lu.end}${lu.totality ? `; totality ${lu.totality}` : ''}. `
        + `At ${m.place} the Moon is ${lu.moonAlt > 0 ? `${lu.moonAlt.toFixed(0)}° up at the peak (visible)` : 'below the horizon at the peak'}.${now(lu.now)}`,
      `- Solar, seen from ${m.place}: ${ls.kind} there, peak ${ls.date} with ${Math.round(ls.covered * 100)}% of the Sun's disc covered, `
        + `Sun ${ls.sunAlt.toFixed(0)}° up; ${ls.start}–${ls.end}.${now(ls.now)}`,
      `- Solar, anywhere on Earth: ${g.kind}, greatest ${g.date}${g.greatest ? ` at ${g.greatest}` : ''}.`);
    if (g.centralLine.length) {
      L.push(`  - Central line (where the axis of the Moon's shadow meets the Earth; the ${g.kind === 'annular' ? 'annular' : 'total'} path runs along it, `
        + 'its width is not computed here). First and last points are where the line begins at sunrise and ends at sunset:');
      for (const p of g.centralLine) L.push(`    - ${p.time}: ${p.at}`);
    }
  }
  if (o.events.length) {
    L.push('', '## Recent events (newest first)');
    for (const e of o.events) L.push(`- ${e.date}: ${strip(e.text)}`);
  }
  L.push('', '---',
    'Snapshot generated by the Astrodynamics orrery (positions computed offline). Please explain from the data above.');
  return L.join('\n');
}

function signEmphasis(chart: Chart): string {
  const counts = new Map<number, number>();
  for (const p of chart.positions) {
    const s = signIndex(p.lon);
    counts.set(s, (counts.get(s) ?? 0) + 1);
  }
  const stellia = [...counts.entries()].filter(([, n]) => n >= 3)
    .map(([s, n]) => `${n} bodies in ${SIGN_NAMES[s]}`);
  return stellia.length ? `Sign emphasis: ${stellia.join('; ')}.` : '';
}
